#!/usr/bin/env python3
"""Generate host adapters (Codex + Claude Code) from the canonical agents/*.md.

agents/<name>.md is the single source of truth for every agent (YAML
frontmatter: description / tools / user-invocable, optional model, then
the body). Two thin GENERATED adapters point back at it:
  .codex/agents/<name>.toml   — Codex custom agent
  .claude/agents/<name>.md    — Claude Code subagent type (so a dispatched
                                seat shows up by NAME in the agent list)
Never edit the adapters by hand; `model:` (sonnet | opus | haiku) pins the
tier on both hosts, absent = inherit. `codex-network: localhost` marks
Codex app-practice seats that need repo-scoped localhost access and their
own seats/<pid> state folder.

    python3 scripts/sync_codex_agents.py            # write missing/stale, drop orphans
    python3 scripts/sync_codex_agents.py --check    # exit 1 + one ERROR line per problem

Also validates skills/<name>/SKILL.md frontmatter (name == directory,
description present) so skills follow the Agent Skills convention.
Requires Python >= 3.11 (tomllib).
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path

MARKER = "# Generated by scripts/sync_codex_agents.py. Do not edit."
MARKER_MD = "<!-- Generated by scripts/sync_codex_agents.py. Do not edit. -->"
TOOLS = ("read", "search", "edit", "bash")
# canonical tool → Claude Code tool names (order follows TOOLS)
CLAUDE_TOOLS = {"read": ("Read",), "search": ("Grep", "Glob"),
                "edit": ("Edit", "Write"), "bash": ("Bash",)}
MODELS = ("sonnet", "opus", "haiku")
AGENT_KEYS = ("description", "tools", "user-invocable")
OPTIONAL_KEYS = ("model", "codex-network")
INSTRUCTIONS = (
    "Act as the repository's `{name}` agent. Read `agents/{name}.md` completely "
    "before starting work and follow it as the canonical workflow and safety "
    "contract. Resolve its skill and agent references through the host's native "
    "mechanisms. Preserve equivalent outcomes, safety constraints, and human "
    "gates; report missing capabilities instead of inventing them. "
    "Canonical `user-invocable` is {ui}.")
AGENT_NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
SKILL_NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")
HELP = ("start the file with a line '---', then single-line 'key: value' "
        "fields, then a closing '---'")


class FrontmatterError(ValueError):
    """Frontmatter that does not follow the simple convention."""


# ---------------------------------------------------------------- parsing
def parse_frontmatter(text: str, label: str) -> dict[str, str]:
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise FrontmatterError(f"{label}: missing YAML frontmatter — {HELP}")
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise FrontmatterError(f"{label}: unterminated frontmatter — {HELP}") from None
    fields: dict[str, str] = {}
    for raw in lines[1:end]:
        if not raw.strip():
            continue
        m = re.match(r"^([A-Za-z][\w-]*):(?:\s+(.*))?$", raw)
        if not m or raw[0].isspace():
            raise FrontmatterError(
                f"{label}: cannot parse frontmatter line {raw!r} — only "
                f"single-line 'key: value' scalars are supported (no block "
                f"scalars, no nested lists)")
        key, value = m.group(1), (m.group(2) or "").strip()
        if key in fields:
            raise FrontmatterError(f"{label}: duplicate frontmatter key {key!r}")
        if value in ("", ">", "|", ">-", "|-"):
            raise FrontmatterError(
                f"{label}: frontmatter key {key!r} must be a non-empty single-line value")
        fields[key] = _unquote(value)
    return fields


def _unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def agent_meta_from_text(text: str, label: str) -> dict:
    fields = parse_frontmatter(text, label)
    missing = [k for k in AGENT_KEYS if k not in fields]
    extra = [k for k in fields if k not in AGENT_KEYS + OPTIONAL_KEYS]
    if missing:
        raise FrontmatterError(f"{label}: frontmatter is missing {missing} — required keys "
                               f"are {list(AGENT_KEYS)}")
    if extra:
        raise FrontmatterError(f"{label}: unsupported frontmatter keys {extra} — allowed "
                               f"keys are {list(AGENT_KEYS + OPTIONAL_KEYS)}")
    model = fields.get("model")
    if model is not None and model not in MODELS:
        raise FrontmatterError(f"{label}: 'model' must be one of {list(MODELS)} "
                               f"(absent = inherit the caller's), got {model!r}")
    tools_raw = fields["tools"]
    m = re.match(r"^\[(.*)\]$", tools_raw)
    if not m:
        raise FrontmatterError(f"{label}: 'tools' must be an inline list like "
                               f"'tools: [read, search, edit, bash]', got {tools_raw!r}")
    tools = [t.strip() for t in m.group(1).split(",") if t.strip()]
    bad = [t for t in tools if t not in TOOLS]
    if not tools or bad or len(set(tools)) != len(tools):
        raise FrontmatterError(f"{label}: 'tools' entries must be unique and from "
                               f"{list(TOOLS)}; got {tools_raw!r}"
                               + (f" (unknown: {bad})" if bad else ""))
    ui = fields["user-invocable"]
    if ui not in ("true", "false"):
        raise FrontmatterError(f"{label}: 'user-invocable' must be true or false, got {ui!r}")
    codex_network = fields.get("codex-network")
    if codex_network is not None and codex_network != "localhost":
        raise FrontmatterError(
            f"{label}: 'codex-network' must be 'localhost' when present, "
            f"got {codex_network!r}")
    return {"description": fields["description"], "tools": tuple(tools),
            "user_invocable": ui == "true", "model": model,
            "codex_network": codex_network}


def load_agents(root: Path) -> tuple[dict[str, dict], list[str]]:
    agents: dict[str, dict] = {}
    errors: list[str] = []
    for md in sorted((root / "agents").glob("*.md")):
        label = f"agents/{md.name}"
        if not AGENT_NAME_RE.match(md.stem):
            errors.append(f"{label}: agent file stem must be lowercase-hyphen")
            continue
        try:
            agents[md.stem] = agent_meta_from_text(md.read_text(), label)
        except FrontmatterError as e:
            errors.append(str(e))
    return agents, errors


def check_skills(root: Path) -> list[str]:
    errors: list[str] = []
    skills = root / "skills"
    if not skills.is_dir():
        return errors
    for d in sorted(p for p in skills.iterdir() if p.is_dir()):
        skill = d / "SKILL.md"
        label = f"skills/{d.name}/SKILL.md"
        if not skill.exists():
            errors.append(f"{label}: missing")
            continue
        try:
            fields = parse_frontmatter(skill.read_text(), label)
        except FrontmatterError as e:
            errors.append(str(e))
            continue
        name = fields.get("name")
        if name is None:
            errors.append(f"{label}: frontmatter needs 'name: {d.name}'")
        elif name != d.name or not SKILL_NAME_RE.match(name):
            errors.append(f"{label}: frontmatter name {name!r} must equal the directory "
                          f"name {d.name!r} (lowercase-hyphen, max 64 chars)")
        desc = fields.get("description")
        if not desc:
            errors.append(f"{label}: frontmatter needs a single-line 'description:'")
        elif len(desc) > 1024:
            errors.append(f"{label}: description longer than 1024 chars")
    return errors


# -------------------------------------------------------------- rendering
def codex_sandbox_mode(meta: dict) -> str | None:
    if meta.get("codex_network") == "localhost":
        return "workspace-write"
    if "edit" not in meta["tools"]:
        return "read-only"
    return None


def render_toml(name: str, meta: dict) -> str:
    ui = "true" if meta["user_invocable"] else "false"
    lines = [
        MARKER,
        f"name = {json.dumps(name)}",
        f"description = {json.dumps(meta['description'])}",
        f"developer_instructions = {json.dumps(INSTRUCTIONS.format(name=name, ui=ui))}",
    ]
    if meta.get("model"):
        lines.append(f"model = {json.dumps(meta['model'])}")
    sandbox_mode = codex_sandbox_mode(meta)
    if sandbox_mode:
        lines.append(f"sandbox_mode = {json.dumps(sandbox_mode)}")
    return "\n".join(lines) + "\n"


def render_claude_md(name: str, meta: dict) -> str:
    """The Claude Code subagent adapter: frontmatter the host reads (name,
    description, tools, optional model) and a body that sends the agent to
    the canonical file. The marker makes it recognisable as generated."""
    tools = [t for c in TOOLS if c in meta["tools"] for t in CLAUDE_TOOLS[c]]
    lines = ["---", f"name: {name}", f"description: {meta['description']}",
             f"tools: [{', '.join(tools)}]"]
    if meta.get("model"):
        lines.append(f"model: {meta['model']}")
    lines += ["---", MARKER_MD, "",
              INSTRUCTIONS.format(name=name,
                                  ui="true" if meta["user_invocable"] else "false")]
    return "\n".join(lines) + "\n"


def _managed_md(path: Path) -> bool:
    try:
        return "Generated by scripts/sync_codex_agents.py" in path.read_text(encoding="utf-8")
    except OSError:
        return False


def _first_line(path: Path) -> str:
    with path.open(encoding="utf-8") as fh:
        return fh.readline().rstrip("\n")


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def _validate_generated(name: str, meta: dict, text: str) -> list[str]:
    import tomllib
    label = f".codex/agents/{name}.toml"
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        return [f"{label}: invalid TOML ({e})"]
    errs = []
    for key in ("name", "description", "developer_instructions"):
        if not isinstance(data.get(key), str) or not data[key].strip():
            errs.append(f"{label}: '{key}' must be a non-empty string")
    if data.get("name") != name:
        errs.append(f"{label}: name {data.get('name')!r} != file stem {name!r}")
    if f"agents/{name}.md" not in str(data.get("developer_instructions", "")):
        errs.append(f"{label}: developer_instructions must reference agents/{name}.md")
    sandbox_mode = codex_sandbox_mode(meta)
    if data.get("sandbox_mode") != sandbox_mode:
        errs.append(f"{label}: sandbox_mode inconsistent with tools {list(meta['tools'])}")
    if data.get("model") != meta.get("model"):
        errs.append(f"{label}: model {data.get('model')!r} != canonical {meta.get('model')!r}")
    return errs


# The two adapter kinds share one check/sync loop.
ADAPTERS = (
    {"dir": (".codex", "agents"), "ext": ".toml", "host": "Codex",
     "render": render_toml, "managed": lambda p: _first_line(p) == MARKER,
     "validate": _validate_generated},
    {"dir": (".claude", "agents"), "ext": ".md", "host": "Claude",
     "render": render_claude_md, "managed": _managed_md,
     "validate": lambda name, meta, text: []},
)


# ---------------------------------------------------------------- actions
def check(root: Path) -> list[str]:
    root = Path(root)
    agents, errors = load_agents(root)
    errors += check_skills(root)
    for kind in ADAPTERS:
        adir = root.joinpath(*kind["dir"])
        rel = "/".join(kind["dir"])
        for name, meta in agents.items():
            path = adir / f"{name}{kind['ext']}"
            label = f"{rel}/{path.name}"
            if not path.exists():
                errors.append(f"{label}: missing adapter — run scripts/sync_codex_agents.py")
                continue
            text = path.read_text(encoding="utf-8")
            if not kind["managed"](path):
                errors.append(f"{label}: unmanaged adapter (no generated marker) — author "
                              f"the canonical agents/{name}.md first, then delete the "
                              f"adapter and re-run the sync")
                continue
            if text != kind["render"](name, meta):
                errors.append(f"{label}: stale or manually changed adapter — run "
                              f"scripts/sync_codex_agents.py")
                continue
            errors += kind["validate"](name, meta, text)
        if adir.is_dir():
            for f in sorted(adir.glob(f"*{kind['ext']}")):
                if f.stem in agents:
                    continue
                if kind["managed"](f):
                    errors.append(f"{rel}/{f.name}: orphaned generated adapter (no "
                                  f"agents/{f.stem}.md) — run the sync to remove it")
                else:
                    errors.append(f"{rel}/{f.name}: unmanaged {kind['host']}-only adapter "
                                  f"— author the canonical agents/{f.stem}.md first")
    return errors


def sync(root: Path, out=None) -> list[str]:
    root = Path(root)
    say = out or (lambda *_: None)
    agents, errors = load_agents(root)
    errors += check_skills(root)
    for kind in ADAPTERS:
        adir = root.joinpath(*kind["dir"])
        rel = "/".join(kind["dir"])
        for name, meta in agents.items():
            path = adir / f"{name}{kind['ext']}"
            want = kind["render"](name, meta)
            if path.exists():
                if not kind["managed"](path):
                    errors.append(f"{rel}/{path.name}: unmanaged adapter — refusing to "
                                  f"overwrite; author the canonical agents/{name}.md "
                                  f"first, then delete the adapter and re-run the sync")
                    continue
                if path.read_text(encoding="utf-8") == want:
                    continue
            _atomic_write(path, want)
            say(f"wrote {rel}/{path.name}")
        if adir.is_dir():
            for f in sorted(adir.glob(f"*{kind['ext']}")):
                if f.stem in agents:
                    continue
                if kind["managed"](f):
                    f.unlink()
                    say(f"removed orphaned {rel}/{f.name}")
                else:
                    errors.append(f"{rel}/{f.name}: unmanaged {kind['host']}-only adapter "
                                  f"— left untouched; author the canonical "
                                  f"agents/{f.stem}.md first")
    return errors


def main(argv=None) -> int:
    if sys.version_info < (3, 11):
        print("ERROR: scripts/sync_codex_agents.py needs Python >= 3.11 (tomllib); "
              f"running {sys.version.split()[0]}", file=sys.stderr)
        return 2
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--root", default=str(Path(__file__).resolve().parent.parent),
                   help="repository root (default: this script's parent's parent)")
    p.add_argument("--check", action="store_true",
                   help="verify adapters without writing; exit 1 if anything is off")
    args = p.parse_args(argv)
    root = Path(args.root)
    if args.check:
        errors = check(root)
    else:
        errors = sync(root, out=print)
    for e in errors:
        print(f"ERROR {e}")
    if not errors:
        print("adapters in sync" if args.check else "adapters synced")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
